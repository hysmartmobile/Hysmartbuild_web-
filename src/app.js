export function createApp({ service = new AppService({ supabase: supabaseAdmin }), supabase = supabaseAdmin } = {}) {
  const app = express();
  const rateLimiter = new InMemoryRateLimiter({ windowMs: 60_000, max: 60 });
  const authMiddleware = createAuthMiddleware({ supabase });
  const authService = new AuthService({ supabase });
  const companyService = new CompanyService({ supabase, webAppUrl: env.webAppUrl });
  const rbacService = new RbacService({ supabase });
  const projectService = new ProjectService({ supabase });
  const workService = new WorkService({ supabase });
  const reportService = new ReportService({ supabase });
  const materialService = new MaterialService({ supabase });
  const workforceService = new WorkforceService({ supabase });
  const financeService = new FinanceService({ supabase });
  const documentService = new DocumentService({ supabase });
  const communicationService = new CommunicationService({ supabase });
  const analyticsService = new AnalyticsService({ supabase });
  const syncService = new SyncService({ supabase, projectService, workService, reportService, workforceService, materialService });
  const supplierService = new SupplierService({ supabase });
  const auditService = new AuditService({ supabase });
  const adminService = new AdminService({ supabase });
  const customerCareLocalModel = new CustomerCareLocalModel({ baseUrl: env.customerCareLocalModelUrl, model: env.customerCareLocalModelName });
  const supportService = new SupportService({ supabase, aiProvider: customerCareLocalModel });
  const procurementAccountingService = new ProcurementAccountingService({ supabase });
  const constructionErpService = new ConstructionErpService({ supabase, procurementAccountingService });
  const scheduleService = new ScheduleService({ supabase });
  const executionService = new ExecutionService({ supabase });
  const siteIntelligenceService = new SiteIntelligenceService({ supabase });
  const qualityService = new QualityService({ supabase });
  const collaborationService = new CollaborationService({ supabase });
  const workflowService = new WorkflowService({ supabase });
  const myWorkService = new MyWorkService({ supabase });
  const executiveIntelligenceService = new ExecutiveIntelligenceService({ supabase });
  const treasuryService = new TreasuryService({ supabase });
  const controlTowerService = new ControlTowerService({ executiveIntelligenceService, treasuryService, workflowService });
  const recoveryService = new RecoveryService({ supabase, executiveIntelligenceService, workflowService });
  const recoveryIntelligenceService = new RecoveryIntelligenceService({ executiveIntelligenceService, treasuryService });
  const fieldRecoveryService = new FieldRecoveryService({ supabase, recoveryService });
  const revenueMarginService = new RevenueMarginService({ supabase });
  const workfrontProductionService = new WorkfrontProductionService({ supabase });
  const operatingSystemService = new OperatingSystemService({ supabase, controlTowerService, revenueMarginService, workfrontProductionService });
  const procurementRiskService = new ProcurementRiskService({ supabase });
  const claimsIntelligenceService = new ClaimsIntelligenceService({ supabase });
  const truthEngineService = new TruthEngineService({ supabase, controlTowerService, revenueMarginService, workfrontProductionService, procurementRiskService, claimsIntelligenceService, treasuryService, operatingSystemService });
  const aiIntelligenceService = new AiIntelligenceService({ truthEngineService, operatingSystemService, supabase, localModel: customerCareLocalModel, localModelEnabled: env.projectAiEnabled });
  const scheduleForecastService = new ScheduleForecastService({ supabase });
  const peopleService = new PeopleService({ supabase });
  const constructionAutopilotService = new ConstructionAutopilotService({ supabase, workflowService, truthEngineService });
  const evidenceEngineService = new EvidenceEngineService({ supabase });
  const constructionNetworkService = new ConstructionNetworkService({ supabase, webAppUrl: env.webAppUrl });
  const realityLayerService = new RealityLayerService({ supabase });
  const financialIntelligenceService = new FinancialIntelligenceService({ supabase });
  const projectCostPlanningService = new ProjectCostPlanningService({ supabase });
  const costForecastLearningService = new CostForecastLearningService({ supabase });
  const cashflowForecastLearningService = new CashflowForecastLearningService({ supabase });
  const lifecycleIntelligenceService = new LifecycleIntelligenceService({ supabase });
  const constructionTypeProfileService = new ConstructionTypeProfileService({ supabase });
  const billingService = new BillingService({
    supabase,
    paystack: env.paystackSecretKey ? new PaystackProvider({ secretKey: env.paystackSecretKey, callbackUrl: env.billingCallbackUrl }) : null,
    flutterwave: env.flutterwaveSecretKey ? new FlutterwaveProvider({ secretKey: env.flutterwaveSecretKey, secretHash: env.flutterwaveSecretHash, callbackUrl: env.billingCallbackUrl }) : null,
    stripe: env.stripeSecretKey ? new StripeProvider({ secretKey: env.stripeSecretKey, webhookSecret: env.stripeWebhookSecret, callbackUrl: env.billingCallbackUrl }) : null,
    callbackUrl: env.billingCallbackUrl
  });
  const authorize = createAuthorizationMiddleware({ rbacService });

  app.disable("x-powered-by");
  app.set("trust proxy", env.trustProxy);
  app.use(helmet());
  const allowedOrigins = new Set(env.corsOrigin.split(",").map((item) => item.trim()).filter(Boolean));
  app.use(cors({
    origin(origin, callback) {
      if (!origin) return callback(null, true);
      if (allowedOrigins.has(origin)) return callback(null, true);
      if (env.nodeEnv === "development") {
        try {
          const url = new URL(origin);
          if (["localhost", "127.0.0.1"].includes(url.hostname) && ["http:", "https:"].includes(url.protocol)) return callback(null, true);
        } catch {}
      }
      return callback(new Error("CORS origin not allowed"));
    },
    credentials: true
  }));
  app.use(express.json({ limit: "1mb", verify: (req, _res, buf) => { req.rawBody = Buffer.from(buf); } }));
  app.use(requestId);
  app.use(auditRequest({ supabase }));

  app.get("/", (_req, res) => res.json({ success: true, data: { name: "HySmart Build API", version: "5.12.0", status: "ok" } }));
  app.use(`${env.apiPrefix}/health`, createHealthRouter({ service }));
  app.use(`${env.apiPrefix}/auth`, createAuthRouter({ supabase, rateLimiter }));
  app.use(`${env.apiPrefix}/me`, createMeRouter({ authService, companyService, authMiddleware }));
  app.use(`${env.apiPrefix}/companies`, createCompaniesRouter({ companyService, authMiddleware, authorize, auditService }));
  app.use(`${env.apiPrefix}/rbac`, createRbacRouter({ rbacService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createAdminRouter({ adminService, supportService, authMiddleware }));
  app.use(`${env.apiPrefix}`, createSupportRouter({ supportService, authMiddleware }));
  app.use(`${env.apiPrefix}`, createProjectsRouter({ projectService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createWorkRouter({ workService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createReportsRouter({ reportService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createMaterialsRouter({ materialService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createWorkforceRouter({ workforceService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createFinanceRouter({ financeService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createDocumentsRouter({ documentService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createCommunicationRouter({ communicationService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createAnalyticsRouter({ analyticsService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createBillingRouter({ billingService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createSyncRouter({ syncService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createSupplierRouter({ supplierService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createProcurementAccountingRouter({ service: procurementAccountingService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createConstructionErpRouter({ service: constructionErpService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createScheduleRouter({ service: scheduleService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createExecutionRouter({ service: executionService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createSiteIntelligenceRouter({ service: siteIntelligenceService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createQualityRouter({ service: qualityService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createCollaborationRouter({ service: collaborationService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createWorkflowRouter({ service: workflowService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createMyWorkRouter({ service: myWorkService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createExecutiveIntelligenceRouter({ service: executiveIntelligenceService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createTreasuryRouter({ service: treasuryService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createControlTowerRouter({ service: controlTowerService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createRecoveryRouter({ service: recoveryService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createRecoveryIntelligenceRouter({ service: recoveryIntelligenceService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createFieldRecoveryRouter({ service: fieldRecoveryService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createRevenueMarginRouter({ service: revenueMarginService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createWorkfrontProductionRouter({ service: workfrontProductionService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createOperatingSystemRouter({ service: operatingSystemService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createStrategicIntelligenceRouter({ procurementRiskService, claimsIntelligenceService, truthEngineService, aiIntelligenceService, scheduleForecastService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createPeopleRouter({ peopleService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createConstructionAutopilotRouter({ service: constructionAutopilotService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createEvidenceEngineRouter({ service: evidenceEngineService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createConstructionNetworkRouter({ service: constructionNetworkService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createRealityLayerRouter({ service: realityLayerService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createFinancialIntelligenceRouter({ service: financialIntelligenceService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createProjectCostPlanningRouter({ service: projectCostPlanningService, learningService: costForecastLearningService, cashflowLearningService: cashflowForecastLearningService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createLifecycleIntelligenceRouter({ service: lifecycleIntelligenceService, authMiddleware, authorize }));
  app.use(`${env.apiPrefix}`, createConstructionTypeProfilesRouter({ service: constructionTypeProfileService, authMiddleware, authorize }));

  app.use((_req, res) => res.status(404).json({ success: false, error: { code: "NOT_FOUND", message: "Route not found" } }));
  app.use(errorHandler);
  return app;
}
