-- V0.1 infrastructure health marker.
-- This table is intentionally tiny and contains no business data.
-- Business tables, RLS policies and tenant model are introduced in V0.2.

create table if not exists public.hysmart_system_health (
  id bigint generated by default as identity primary key,
  service_name text not null default 'hysmart-build',
  created_at timestamptz not null default now()
);

insert into public.hysmart_system_health (service_name)
select 'hysmart-build'
where not exists (
  select 1 from public.hysmart_system_health
);
